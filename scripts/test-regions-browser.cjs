const {chromium} = require('playwright');
const assert = require('node:assert/strict');
let input = '';
process.stdin.on('data', chunk => input += chunk);
process.stdin.on('end', async () => {
  const {url, sessions, ids, pdf, expires, appointmentDay, unavailableDay} = JSON.parse(input);
  const browser = await chromium.launch({headless:true, ...(process.env.SEVLINK_CHROMIUM_PATH ? {executablePath:process.env.SEVLINK_CHROMIUM_PATH} : {}), args:['--no-sandbox']});
  const errors = [], requests = [];
  try {
    const context = await browser.newContext({viewport:{width:1440,height:900}});
    await context.addCookies([{name:'sessionid',value:sessions.ops,url}]);
    const page = await context.newPage(); page.setDefaultTimeout(10000);
    page.on('pageerror', error => errors.push(error.message));
    page.on('response',r=>{if(r.url().includes('/api/') || r.url().includes('/logout/')) requests.push([new URL(r.url()).pathname,r.status()]);});
    await page.goto(url+'/maintenance/');
    await page.locator('#app .stats').waitFor();
    await page.locator('#nav [data-view=regions]').click();
    await page.getByRole('heading',{name:'Service areas & assignments'}).waitFor();
    await page.locator('#regionFilterProvince').selectOption(String(ids.wc));
    await page.locator(`[data-regional-job="${ids.gpjob}"]`).waitFor({state:'detached'});
    await page.locator('#regionFilterCity option').filter({hasText:'Cape Town'}).waitFor({state:'attached'});
    await page.locator('#regionFilterCity').selectOption(String(ids.cape));
    await page.locator(`[data-regional-job="${ids.job}"]`).waitFor();
    assert.equal(await page.locator(`[data-regional-job="${ids.gpjob}"]`).count(),0);
    await page.locator(`[data-regional-job="${ids.job}"]`).click();
    await page.locator('#regionAssignment').waitFor();
    const names = await page.locator('#regionAssignment option').allTextContents();
    assert(names.includes('PRIVATE multi-region partner'));
    assert(!names.includes('PRIVATE Gauteng only'));
    assert(!names.includes('PRIVATE inactive'));
    await page.locator('#regionAssignment [name=subcontractor]').selectOption(ids.partner);
    await page.getByRole('button',{name:'Record assignment',exact:true}).click();
    await page.locator('#modal p').filter({hasText:'PRIVATE multi-region partner ·'}).waitFor();
    await page.getByRole('button',{name:'Close',exact:true}).click();
    await page.locator('#newSubcontractor').click();
    await page.locator('#regionContractor [name=name]').fill('Browser dual-region partner');
    await page.locator('#regionContractor [name=cities]').selectOption([String(ids.cape),String(ids.joburg)]);
    await page.getByRole('button',{name:'Save service areas'}).click();
    await page.locator('td').filter({hasText:'Browser dual-region partner'}).waitFor();
    await page.locator(`[data-supplier="${ids.partner}"]`).click();
    await page.locator('#supplierProfileForm [name=contact_person]').fill('Synthetic browser contact');
    await page.locator('#supplierProfileForm [name=email]').fill('synthetic-browser@example.test');
    await page.locator('#supplierProfileForm [name=internal_notes]').fill('PRIVATE browser supplier note');
    await page.locator('#supplierProfileForm [name=trades]').selectOption('Plumbing');
    const oldProfileVersion=await page.locator('#supplierProfileForm').getAttribute('data-version');
    await page.getByRole('button',{name:'Save private profile',exact:true}).click();
    await page.waitForFunction(old => document.querySelector('#supplierProfileForm')?.dataset.version !== old,oldProfileVersion);
    assert.equal(await page.locator('#supplierProfileForm [name=contact_person]').inputValue(),'Synthetic browser contact');
    assert.equal(await page.locator('#supplierBank').count(),0,'Bank details require an explicit finance grant');
    assert.equal((await page.request.get(url+`/api/maintenance/operations/subcontractors/${ids.partner}/bank/`)).status(),403);
    for (const name of ['Team A','Team B']) {
      await page.locator('#supplierNewTeam').click();
      await page.locator('#supplierTeam [name=name]').fill(name);
      await page.locator('#supplierTeam [name=working_days][value="0"]').check();
      await page.getByRole('button',{name:'Save team',exact:true}).click();
      await page.locator('#supplierProfile .panel').filter({has:page.getByRole('heading',{name,exact:true})}).waitFor();
    }
    await page.locator('#supplierDocument [name=title]').fill('Synthetic public liability insurance');
    await page.locator('#supplierDocument [name=kind]').selectOption('insurance');
    await page.locator('#supplierDocument [name=expires_on]').fill(expires);
    await page.locator('#supplierDocument [name=attachments]').setInputFiles({name:'insurance.pdf',mimeType:'application/pdf',buffer:Buffer.from(pdf,'base64')});
    await page.getByRole('button',{name:'Upload compliance PDF',exact:true}).click();
    const documentLink=page.getByRole('link',{name:'Synthetic public liability insurance',exact:true});
    await documentLink.waitFor();
    assert.equal((await page.request.get(url+await documentLink.getAttribute('href'))).status(),200);
    await page.getByRole('button',{name:'Close',exact:true}).click();
    await page.locator(`[data-regional-job="${ids.job}"]`).click();
    await page.locator('#regionAssignment [name=subcontractor]').selectOption(ids.partner);
    await page.locator('#regionAssignment [name=team]').selectOption({label:'Team A'});
    await page.getByRole('button',{name:'Record assignment',exact:true}).click();
    await page.locator('#modal p').filter({hasText:'Team A'}).waitFor();
    await page.getByRole('button',{name:'Close',exact:true}).click();
    await page.locator(`[data-supplier="${ids.partner}"]`).click();
    const teamA=page.locator('#supplierProfile .panel').filter({has:page.getByRole('heading',{name:'Team A',exact:true})});
    await teamA.locator('.supplierAppointment [name=assignment]').selectOption({index:1});
    await teamA.locator('.supplierAppointment [name=starts_at]').fill(appointmentDay+'T10:00');
    await teamA.locator('.supplierAppointment [name=ends_at]').fill(appointmentDay+'T11:00');
    await teamA.getByRole('button',{name:'Record appointment',exact:true}).click();
    await page.locator('.supplierCancelAppointment').waitFor();
    await teamA.locator('.supplierUnavailable [name=date]').fill(unavailableDay);
    await teamA.locator('.supplierUnavailable [name=reason]').fill('Synthetic unavailable date');
    await teamA.getByRole('button',{name:'Add unavailable date',exact:true}).click();
    await page.getByText('Synthetic unavailable date',{exact:false}).waitFor();
    await page.locator('#supplierAgreement [name=commission_percent]').fill('12.50');
    await page.locator('#supplierAgreement [name=rate]').fill('450.25');
    await page.locator('#supplierAgreement [name=terms]').fill('PRIVATE browser agreement');
    await page.getByRole('button',{name:'Record agreement',exact:true}).click();
    await page.locator('#supplierProfile p').filter({hasText:'PRIVATE browser agreement'}).waitFor();
    await page.getByRole('button',{name:'Close',exact:true}).click();
    await page.locator('#nav [data-view=regions]').click();
    await page.getByRole('heading',{name:'Compliance expiry alerts (1)',exact:true}).waitFor();
    assert.equal(await page.evaluate(() => indexedDB.databases().then(d => d.length)),0);
    await context.close();
    const pm = await browser.newContext();
    await pm.addCookies([{name:'sessionid',value:sessions.pm,url}]);
    const pmPage = await pm.newPage();
    await pmPage.goto(url+'/maintenance/');
    await pmPage.locator('#nav [data-view=requests]').waitFor();
    assert.equal(await pmPage.locator('[data-view=regions]').count(),0);
    assert.equal((await pmPage.request.get(url+'/api/maintenance/operations/regions/')).status(),403);
    const body = await (await pmPage.request.get(url+'/api/maintenance/requests/')).text();
    assert(!body.includes('PRIVATE multi-region partner'));
    assert(!body.includes('job_assigned'));
    assert(!body.includes('PRIVATE browser supplier note'));
    assert(!body.includes('PRIVATE browser agreement'));
    assert(!body.includes('synthetic-browser@example.test'));
    await pm.close();
    assert.deepEqual(errors,[]);
    console.log('PASS: regional filtering, private coverage-based assignment and multi-area registration, private profiles, teams, compliance PDFs, expiry reminders, agreements and appointments in the existing Operations portal; PM and finance isolation.');
  } catch(error) { console.error('HTTP diagnostic:',JSON.stringify(requests));throw error; } finally { await browser.close(); }
});
